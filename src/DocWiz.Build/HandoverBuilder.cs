using System.Text;
using System.Text.Json;
using DocWiz.Core.Loading;
using DocWiz.Core.Markdown;
using DocWiz.Core.Models;
using Markdig;
using Markdig.Renderers.Html;
using Markdig.Syntax;
using Markdig.Syntax.Inlines;

namespace DocWiz.Build;

public sealed class DocWizBuildException(string message) : Exception(message);

/// <summary>
/// Generates the offline handover site (full manual) from a loaded, parsed, validated
/// project. Views rendering is the Stage 2 extension point. Re-runnable: wipes and
/// rewrites the output directory each time.
/// </summary>
public static class HandoverBuilder
{
    public static string Build(DocProject project, MarkdownPipeline pipeline, string outDir)
    {
        outDir = Path.GetFullPath(outDir);
        if (Directory.Exists(outDir))
            Directory.Delete(outDir, recursive: true);
        Directory.CreateDirectory(outDir);

        // Every generated page + asset folder lives under _site/, leaving the output root
        // holding only folders + the one project-named entry html (so a manager knows what
        // to open). Pages inside _site/ keep flat, sibling-relative links exactly as before;
        // only the chrome carries {{BASE}}/{{HOME}} prefixes resolved per page (see ApplyBase).
        var siteDir = Path.Combine(outDir, SiteFolder);
        Directory.CreateDirectory(siteDir);
        WriteStaticAssets(siteDir);
        CopyFolder(project.AssetsDir, Path.Combine(siteDir, ProjectLayout.AssetsFolder));
        CopyFolder(project.AttachmentsDir, Path.Combine(siteDir, ProjectLayout.AttachmentsFolder));
        var externalDocs = CopyExternalDocs(project, siteDir);
        var attachments = ListAttachments(project);
        // Word-style numbering (sections 1, chapters 1.1; headings via CSS counters).
        var nums = project.Manifest.Numbering ? NumberChapters(project) : null;

        var template = ReadTemplate("base.html");
        var slidesTemplate = ReadTemplate("slides.html");
        var generated = $"generated by DocWiz on {DateTime.Now:yyyy-MM-dd HH:mm}";
        var manualTabs = BuildTabs(project, activeId: "manual", externalDocs, attachments.Count > 0);

        WriteSearchIndex(project, pipeline, Path.Combine(siteDir, "_dw", "search-index.js"));

        // Views are rendered BEFORE the chapter pages so transclusion reads each chapter's
        // PRISTINE AST. The chapter-page loop below calls LinkRewriter.Rewrite, which mutates
        // the shared chapter.Parsed in place — for a MISSING asset it removes the image inline
        // (replacing it with a placeholder span). An element embed (`::: embed dw:ch#figure-1`)
        // resolves that figure off chapter.Parsed via DocWizFiguresExtension.ImageOf; if the
        // chapter loop ran first, the inline would be gone and the embed would throw at build —
        // even though `docwiz check` reported 0 errors (the anchor is still in chapter.Anchors).
        // Ordering views first keeps the check⇔build invariant. The two loops write disjoint
        // output files (view-<id>.html vs <id>.html) and the views loop reads nothing the
        // chapter loop produces, so this reorder is behavior-preserving for everything else.
        foreach (var view in project.Views)
        {
            var tabs = BuildTabs(project, activeId: view.Id, externalDocs, attachments.Count > 0);
            // Views live in _site/ → site context (base "", home "..").
            var html = view.Mode == "slides"
                ? ApplyBase(slidesTemplate
                    .Replace("{{TITLE}}", Escape(view.Title))
                    .Replace("{{PROJECT}}", Escape(project.Manifest.Project))
                    .Replace("{{CODE}}", Escape(project.Manifest.Code))
                    .Replace("{{VERSION}}", Escape(project.Manifest.Version))
                    .Replace("{{TABS}}", tabs)
                    .Replace("{{SLIDES}}", ViewRenderer.RenderSlides(project, view, pipeline))
                    .Replace("{{GENERATED}}", Escape(generated)), SiteBase, SiteHome)
                : RenderPage(template, project, generated, tabs,
                    title: view.Title,
                    crumb: $"Views / {Escape(view.Title)}",
                    nav: BuildNav(project, current: null, nums),
                    content: ViewRenderer.RenderDocument(project, view, pipeline),
                    prevNext: "        <span class=\"spacer\"></span>");

            File.WriteAllText(Path.Combine(siteDir, ViewFileName(view)), html, Encoding.UTF8);
        }

        for (var i = 0; i < project.Chapters.Count; i++)
        {
            var chapter = project.Chapters[i];
            var doc = chapter.Parsed
                ?? throw new DocWizBuildException($"Chapter '{chapter.Id}' is not parsed — run DocWizMarkdown.ParseAll first.");

            // Mutates chapter.Parsed in place (dw: links → page URLs, missing images →
            // placeholders). Must run AFTER the views loop, which needs the pristine AST.
            LinkRewriter.Rewrite(doc, project, id => $"{id}.html");

            var html = RenderPage(template, project, generated, manualTabs,
                title: chapter.Title,
                crumb: $"{Escape(chapter.SectionTitle)} / {Escape(chapter.Title)}",
                nav: BuildNav(project, current: chapter, nums),
                content: DocWizMarkdown.RenderHtml(doc, pipeline),
                prevNext: BuildPrevNext(project, i, nums),
                articleAttrs: nums is null ? "" : $" data-num style=\"--dwch:'{nums[chapter]}'\"");

            File.WriteAllText(Path.Combine(siteDir, $"{chapter.Id}.html"), html, Encoding.UTF8);
        }

        if (attachments.Count > 0)
            File.WriteAllText(Path.Combine(siteDir, "attachments.html"),
                BuildAttachmentsPage(template, project, generated,
                    BuildTabs(project, activeId: "attachments", externalDocs, true), attachments, nums),
                Encoding.UTF8);

        // One wrapper page per external doc: a slim DocWiz back strip above a full-bleed
        // iframe hosting the embedded doc (copied as-is, ADR-006). Gives touch users a way
        // back to the documentation, which the embedded doc itself provides no link for.
        if (externalDocs.Count > 0)
        {
            var frameTemplate = ReadTemplate("external-frame.html");
            foreach (var (key, title, entry) in externalDocs)
            {
                // key is unescaped here — safe because the validator rejects any key not
                // matching ProjectLayout.IsValidExternalKey (^[a-z0-9_]+$) before build.
                var frameHtml = ApplyBase(frameTemplate
                    .Replace("{{DOCTITLE}}", Escape(title))
                    .Replace("{{CODE}}", Escape(project.Manifest.Code))
                    .Replace("{{HOMEHREF}}", HomeToken + EntryFileName(project.Manifest))
                    .Replace("{{FRAMESRC}}", $"external/{key}/{Uri.EscapeDataString(entry)}"),
                    SiteBase, SiteHome);
                File.WriteAllText(Path.Combine(siteDir, $"external-{key}.html"), frameHtml, Encoding.UTF8);
            }
        }

        // The single root entry/home page: today's index content, but at the output root
        // (entry context: base "_site/", home "") and named after the project.
        File.WriteAllText(Path.Combine(outDir, EntryFileName(project.Manifest)),
            BuildIndexPage(template, project, generated, manualTabs, attachments.Count > 0, nums), Encoding.UTF8);

        return outDir;
    }

    private static string ViewFileName(ViewDefinition view) => $"view-{view.Id}.html";

    /// <summary>The single root entry/home page, named after the project so a manager sees
    /// one obviously-titled file in the output root. Title → code → "handover" fallback;
    /// the editor's /handover redirect resolves the same name (ADR-008 — one authority).</summary>
    public static string EntryFileName(ProjectManifest m)
    {
        var basis = !string.IsNullOrWhiteSpace(m.Project) ? m.Project
                  : !string.IsNullOrWhiteSpace(m.Code) ? m.Code
                  : "handover";
        return Packager.FileNameSafe(basis) + ".html";
    }

    /// <summary>Audience switcher in the chrome: Manual, one tab per view, the
    /// Attachments page, and one tab per embedded external documentation package
    /// (API reference, release notes, … — ADR-006).</summary>
    private static string BuildTabs(DocProject project, string activeId,
        List<(string Key, string Title, string Entry)> externalDocs, bool hasAttachments)
    {
        var sb = new StringBuilder();
        // Home/Manual tab lives at the output root → {{HOME}} prefix; everything else lives
        // under _site/ → {{BASE}} prefix (resolved per page by ApplyBase).
        sb.AppendLine($"    <a href=\"{HomeToken}{EntryFileName(project.Manifest)}\"{(activeId == "manual" ? " class=\"active\"" : "")}>Manual</a>");
        foreach (var view in project.Views)
            sb.AppendLine($"    <a href=\"{BaseToken}{ViewFileName(view)}\"{(activeId == view.Id ? " class=\"active\"" : "")}>{Escape(view.Title)}</a>");
        if (hasAttachments)
            sb.AppendLine($"    <a href=\"{BaseToken}attachments.html\"{(activeId == "attachments" ? " class=\"active\"" : "")}>Attachments</a>");
        foreach (var (key, title, _) in externalDocs)
            sb.AppendLine($"    <a href=\"{BaseToken}external-{key}.html\">{Escape(title)}</a>");
        return sb.ToString();
    }

    /// <summary>Relative forward-slash paths of every attachment file (README excluded).</summary>
    private static List<string> ListAttachments(DocProject project)
    {
        if (!Directory.Exists(project.AttachmentsDir))
            return [];
        return Directory.GetFiles(project.AttachmentsDir, "*", SearchOption.AllDirectories)
            .Select(f => Path.GetRelativePath(project.AttachmentsDir, f).Replace('\\', '/'))
            .Where(n => !string.Equals(Path.GetFileName(n), "README.md", StringComparison.OrdinalIgnoreCase))
            .OrderBy(n => n, StringComparer.OrdinalIgnoreCase)
            .ToList();
    }

    /// <summary>Attachments overview: PDFs embedded inline (browser-native viewer — works
    /// from file:// in Chromium without any JS dependency), everything else as a link.</summary>
    private static string BuildAttachmentsPage(string template, DocProject project, string generated,
        string tabs, List<string> attachments, Dictionary<Chapter, string>? nums = null)
    {
        var content = new StringBuilder();
        content.AppendLine("      <h1>Attachments</h1>");
        content.AppendLine("      <p class=\"lead\">Drawings, datasheets, and documents delivered with " +
                           "this handover. PDFs are shown inline; open in a new tab for full-screen.</p>");

        foreach (var group in attachments.GroupBy(a => a.Contains('/') ? a[..a.LastIndexOf('/')] : ""))
        {
            if (group.Key.Length > 0)
                content.AppendLine($"      <div class=\"grp-label\">{Escape(group.Key)}</div>");
            foreach (var rel in group)
            {
                var url = string.Join('/', rel.Split('/').Select(Uri.EscapeDataString));
                var isPdf = rel.EndsWith(".pdf", StringComparison.OrdinalIgnoreCase);
                content.AppendLine("      <section class=\"attach\">");
                content.AppendLine($"        <h3><span class=\"path\">{Escape(rel)}</span>" +
                                   $"<a class=\"open\" href=\"attachments/{url}\" target=\"_blank\" rel=\"noopener\">open ↗</a></h3>");
                if (isPdf)
                    content.AppendLine($"        <iframe class=\"pdf\" src=\"attachments/{url}\" title=\"{Escape(rel)}\"></iframe>");
                else
                    content.AppendLine($"        <div class=\"file-line\"><a href=\"attachments/{url}\" target=\"_blank\" rel=\"noopener\">Download {Escape(Path.GetFileName(rel))}</a></div>");
                content.AppendLine("      </section>");
            }
        }

        return RenderPage(template, project, generated, tabs,
            title: "Attachments",
            crumb: "Attachments",
            nav: BuildNav(project, current: null, nums),
            content: content.ToString(),
            prevNext: "        <span class=\"spacer\"></span>");
    }

    /// <summary>Writes the client-side search index as a script-tag payload
    /// (window.__dwSearch) so it loads from file:// (fetch of local files is blocked).</summary>
    private static void WriteSearchIndex(DocProject project, MarkdownPipeline pipeline, string path)
    {
        var entries = project.Chapters.Select(c => new
        {
            id = c.Id,
            title = c.Title,
            section = c.SectionTitle,
            url = $"{c.Id}.html",
            text = PlainText(c.Parsed!),
        });
        var json = JsonSerializer.Serialize(entries);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, "window.__dwSearch=" + json + ";", Encoding.UTF8);
    }

    /// <summary>Readable plain text of a chapter for the search index (markup stripped,
    /// whitespace collapsed). Indexes the full chapter so a long chapter's tail stays
    /// searchable; the total index is small for a manual-sized project.</summary>
    private static string PlainText(MarkdownDocument doc)
    {
        var sb = new StringBuilder();
        foreach (var node in doc.Descendants())
        {
            switch (node)
            {
                case LiteralInline li: sb.Append(li.Content.ToString()); sb.Append(' '); break;
                case CodeInline ci: sb.Append(ci.Content); sb.Append(' '); break;
            }
        }
        return string.Join(' ', sb.ToString().Split((char[]?)null, StringSplitOptions.RemoveEmptyEntries));
    }

    /// <summary>Copies every configured external documentation package into the
    /// handover (ADR-006: as-is) under external/&lt;key&gt;/. Returns (key, tab title,
    /// entry page) for each package that was actually copied.</summary>
    private static List<(string Key, string Title, string Entry)> CopyExternalDocs(DocProject project, string outDir)
    {
        var copied = new List<(string, string, string)>();
        foreach (var (key, path) in project.Manifest.ExternalDocs)
        {
            var source = Path.GetFullPath(path, project.Root);
            if (!Directory.Exists(source))
                continue; // validator already warned about the missing folder

            foreach (var file in Directory.GetFiles(source, "*", SearchOption.AllDirectories))
            {
                var dest = Path.Combine(outDir, "external", key, Path.GetRelativePath(source, file));
                Directory.CreateDirectory(Path.GetDirectoryName(dest)!);
                File.Copy(file, dest, overwrite: true);
            }
            // Validator warns when neither candidate exists; default to index.html so the href is well-formed.
            var entry = ProjectLayout.ResolveExternalEntry(source) ?? ProjectLayout.ExternalEntryCandidates[^1];
            copied.Add((key, ExternalTabTitle(key), entry));
        }
        return copied;
    }

    /// <summary>"api_reference" → "API Reference", "release_notes" → "Release Notes",
    /// "vendor_documentation" → "Vendor".</summary>
    public static string ExternalTabTitle(string key)
    {
        var trimmed = key.EndsWith("_documentation", StringComparison.OrdinalIgnoreCase)
            ? key[..^"_documentation".Length]
            : key;
        return ProjectLoader.ToDisplayTitle(trimmed.Replace('_', '-'));
    }

    /// <summary>Word-style flat chapter numbers in nav order: "1", "2", "3", … Section
    /// folders are unnumbered groups (like Word parts); in-page headings continue the
    /// chapter number via CSS counters (N.1, N.1.1). This matches how the existing PDF
    /// manuals are numbered — the section level does not consume a numbering level.</summary>
    private static Dictionary<Chapter, string> NumberChapters(DocProject project)
    {
        var map = new Dictionary<Chapter, string>();
        var chapterNo = 0;
        foreach (var chapter in project.Chapters)
            map[chapter] = $"{++chapterNo}";
        return map;
    }

    private static string NumTitle(Dictionary<Chapter, string>? nums, Chapter chapter) =>
        nums is null ? chapter.Title : $"{nums[chapter]} {chapter.Title}";

    /// <summary>Output subfolder holding every generated page + asset folder; the output
    /// root keeps only this folder and the one entry html. Public so the editor's /handover
    /// route resolves the same name (ADR-008).</summary>
    public const string SiteFolder = "_site";

    // Per-page link prefixes resolved by ApplyBase. {{BASE}} reaches the _site/ root from
    // the current page; {{HOME}} reaches the root entry html. Site pages live inside _site/
    // (base "", home ".."); the entry/home page sits at the root (base "_site/", home "").
    private const string BaseToken = "{{BASE}}";
    private const string HomeToken = "{{HOME}}";
    private const string SiteBase = "";
    private const string SiteHome = "../";
    private const string EntryBase = SiteFolder + "/";
    private const string EntryHome = "";

    /// <summary>Resolves the {{BASE}}/{{HOME}} link prefixes for one page. MUST run after
    /// {{TABS}}/{{NAV}}/{{CONTENT}}/{{PREVNEXT}} are substituted — those fragments carry the
    /// tokens. One helper so RenderPage and the slides branch can't drift (ADR-008).</summary>
    private static string ApplyBase(string html, string @base, string home) =>
        html.Replace(BaseToken, @base).Replace(HomeToken, home);

    private static string RenderPage(string template, DocProject project, string generated, string tabs,
        string title, string crumb, string nav, string content, string prevNext,
        string articleAttrs = "", string @base = SiteBase, string home = SiteHome) => ApplyBase(template
        .Replace("{{ARTICLE_ATTRS}}", articleAttrs)
        .Replace("{{TABS}}", tabs)
        .Replace("{{TITLE}}", Escape(title))
        .Replace("{{PROJECT}}", Escape(project.Manifest.Project))
        .Replace("{{CODE}}", Escape(project.Manifest.Code))
        .Replace("{{VERSION}}", Escape(project.Manifest.Version))
        .Replace("{{CRUMB}}", crumb)
        .Replace("{{NAV}}", nav)
        .Replace("{{CONTENT}}", content)
        .Replace("{{PREVNEXT}}", prevNext)
        .Replace("{{GENERATED}}", Escape(generated)), @base, home);

    private static string BuildNav(DocProject project, Chapter? current,
        Dictionary<Chapter, string>? nums = null)
    {
        var sb = new StringBuilder();
        foreach (var section in project.Chapters.GroupBy(c => c.SectionTitle))
        {
            sb.AppendLine("    <div class=\"nav-group\">");
            sb.AppendLine($"      <div class=\"grp\">{Escape(section.Key)}</div>");
            foreach (var chapter in section)
            {
                var cls = chapter == current ? " class=\"current\"" : "";
                sb.AppendLine($"      <a href=\"{BaseToken}{chapter.Id}.html\"{cls}>{Escape(NumTitle(nums, chapter))}</a>");
                // The open chapter expands into its H2/H3 outline (anchors into the page),
                // mirroring the editor's tree. Numbers continue the chapter number (N.1,
                // N.1.1) to match the page's CSS heading counters.
                if (chapter == current)
                    AppendChapterOutline(sb, chapter, nums);
            }
            sb.AppendLine("    </div>");
        }
        return sb.ToString();
    }

    /// <summary>Sub-links for the current chapter's H2/H3 headings. Reads ids and text off
    /// the parsed AST so the anchors match the heading ids the page actually renders
    /// (AutoIdentifiers/explicit {#anchor}) — no second slug derivation (ADR-008).</summary>
    private static void AppendChapterOutline(StringBuilder sb, Chapter chapter,
        Dictionary<Chapter, string>? nums)
    {
        if (chapter.Parsed is null)
            return;
        var chNum = nums is not null && nums.TryGetValue(chapter, out var n) ? n : null;
        int n2 = 0, n3 = 0;
        foreach (var heading in chapter.Parsed.Descendants<HeadingBlock>())
        {
            if (heading.Level is not (2 or 3))
                continue;
            // Increment before the id check so numbers stay aligned with the CSS counters,
            // which count every h2/h3 in the page regardless of anchor presence.
            var deep = heading.Level == 3;
            if (deep) n3++; else { n2++; n3 = 0; }
            var id = heading.TryGetAttributes()?.Id;
            if (string.IsNullOrEmpty(id))
                continue;
            var prefix = chNum is null ? "" : deep ? $"{chNum}.{n2}.{n3} " : $"{chNum}.{n2} ";
            var subCls = deep ? "nav-sub nav-sub3" : "nav-sub";
            sb.AppendLine($"      <a class=\"{subCls}\" href=\"#{id}\">{Escape(prefix + HeadingText(heading))}</a>");
        }
    }

    /// <summary>Plain text of a heading's inline content (markdown markers dropped).</summary>
    private static string HeadingText(HeadingBlock heading) =>
        heading.Inline is null ? "" :
        string.Concat(heading.Inline.Descendants<LiteralInline>().Select(l => l.Content.ToString())).Trim();

    private static string BuildPrevNext(DocProject project, int index,
        Dictionary<Chapter, string>? nums = null)
    {
        var sb = new StringBuilder();
        if (index > 0)
        {
            var prev = project.Chapters[index - 1];
            sb.AppendLine($"        <a href=\"{BaseToken}{prev.Id}.html\">← {Escape(NumTitle(nums, prev))}</a>");
        }
        sb.AppendLine("        <span class=\"spacer\"></span>");
        if (index < project.Chapters.Count - 1)
        {
            var next = project.Chapters[index + 1];
            sb.AppendLine($"        <a href=\"{BaseToken}{next.Id}.html\">{Escape(NumTitle(nums, next))} →</a>");
        }
        return sb.ToString();
    }

    private static string BuildIndexPage(string template, DocProject project, string generated, string tabs,
        bool hasAttachments, Dictionary<Chapter, string>? nums = null)
    {
        var m = project.Manifest;
        var content = new StringBuilder();
        content.AppendLine($"      <h1>{Escape(m.Project)}</h1>");
        content.AppendLine("      <table class=\"meta-table\">");
        content.AppendLine($"        <tr><td>Project code</td><td class=\"mono\">{Escape(m.Code)}</td></tr>");
        content.AppendLine($"        <tr><td>Customer</td><td>{Escape(m.Customer)}</td></tr>");
        content.AppendLine($"        <tr><td>Documentation version</td><td class=\"mono\">{Escape(m.Version)}</td></tr>");
        content.AppendLine($"        <tr><td>Chapters</td><td>{project.Chapters.Count}</td></tr>");
        content.AppendLine("      </table>");

        if (project.Views.Count > 0)
        {
            content.AppendLine("      <h2>Audience views</h2>");
            content.AppendLine("      <ul>");
            foreach (var view in project.Views)
                content.AppendLine($"        <li><a href=\"{BaseToken}{ViewFileName(view)}\">{Escape(view.Title)}</a>" +
                                   $" — {Escape(view.Audience)}, {Escape(view.Mode)}</li>");
            content.AppendLine("      </ul>");
        }

        if (hasAttachments)
            content.AppendLine($"      <p><a href=\"{BaseToken}attachments.html\">Attachments &amp; drawings →</a></p>");

        content.AppendLine("      <h2>Contents</h2>");
        foreach (var section in project.Chapters.GroupBy(c => c.SectionTitle))
        {
            content.AppendLine($"      <h3>{Escape(section.Key)}</h3>");
            content.AppendLine("      <ul>");
            foreach (var chapter in section)
                content.AppendLine($"        <li><a href=\"{BaseToken}{chapter.Id}.html\">{Escape(NumTitle(nums, chapter))}</a></li>");
            content.AppendLine("      </ul>");
        }

        // The entry/home page sits at the output root → entry context (base "_site/", home "").
        return RenderPage(template, project, generated, tabs,
            title: "Documentation",
            crumb: "Home",
            nav: BuildNav(project, current: null, nums),
            content: content.ToString(),
            prevNext: "        <span class=\"spacer\"></span>",
            @base: EntryBase, home: EntryHome);
    }

    private static void WriteStaticAssets(string outDir)
    {
        var dwDir = Path.Combine(outDir, "_dw");
        Directory.CreateDirectory(dwDir);
        foreach (var name in new[] { "tokens.css", "site.css", "site.js", "slides.js", "search.js", "probe.js" })
            File.WriteAllText(Path.Combine(dwDir, name), ReadTemplate(name), Encoding.UTF8);
    }

    private static void CopyFolder(string source, string target)
    {
        if (!Directory.Exists(source))
            return;
        Directory.CreateDirectory(target);
        foreach (var file in Directory.GetFiles(source, "*", SearchOption.AllDirectories))
        {
            // Folder-level README.md files are project-internal notes, not handover content.
            if (string.Equals(Path.GetFileName(file), "README.md", StringComparison.OrdinalIgnoreCase))
                continue;
            var rel = Path.GetRelativePath(source, file);
            var dest = Path.Combine(target, rel);
            Directory.CreateDirectory(Path.GetDirectoryName(dest)!);
            File.Copy(file, dest, overwrite: true);
        }
    }

    private static string ReadTemplate(string name) => SiteTemplates.Read(name);

    private static string Escape(string text) => WebUtility.HtmlEncode(text);
}
