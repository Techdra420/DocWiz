using System.Net;
using System.Text;
using System.Text.RegularExpressions;
using DocWiz.Core.Models;
using Markdig;

namespace DocWiz.Build;

/// <summary>
/// Exports one audience view as a single self-contained .html file: CSS and JS inlined,
/// images embedded as base64 data URIs. For training-only / small packages that a manager
/// can email (ADR-003). PDFs are not inlined — single-file export is for slide/document
/// views, not the attachment-heavy administrator handover.
/// </summary>
public static partial class SingleFileExporter
{
    public static string ExportView(DocProject project, ViewDefinition view, MarkdownPipeline pipeline)
    {
        var m = project.Manifest;
        string html = view.Mode == "slides"
            ? SiteTemplates.Read("slides.html")
                .Replace("{{TABS}}", "")
                .Replace("{{SLIDES}}", ViewRenderer.RenderSlides(project, view, pipeline))
            : DocumentShell(ViewRenderer.RenderDocument(project, view, pipeline, linkSources: false));

        html = html
            .Replace("{{TITLE}}", Escape(view.Title))
            .Replace("{{PROJECT}}", Escape(m.Project))
            .Replace("{{CODE}}", Escape(m.Code))
            .Replace("{{VERSION}}", Escape(m.Version))
            .Replace("{{GENERATED}}", Escape($"generated by DocWiz on {DateTime.Now:yyyy-MM-dd HH:mm}"));

        return InlineAssets(html, project);
    }

    /// <summary>Exports one or more chapters as a single self-contained .html file (CSS/JS inlined,
    /// images base64). chapterIds == null = the whole manual; otherwise those chapters in book
    /// order. External PDF drawings are not embedded — each is shown as an in-place attachment
    /// note (ADR-003), via the shared ChapterDocumentAssembler.</summary>
    public static string ExportChapters(DocProject project, MarkdownPipeline pipeline,
                                        IReadOnlyCollection<string>? chapterIds = null)
    {
        var m = project.Manifest;
        var body = ChapterDocumentAssembler.AssembleBody(project, pipeline, chapterIds);
        var html = DocumentShell(body)
            .Replace("{{TITLE}}", Escape(m.Project))
            .Replace("{{PROJECT}}", Escape(m.Project))
            .Replace("{{CODE}}", Escape(m.Code))
            .Replace("{{VERSION}}", Escape(m.Version))
            .Replace("{{GENERATED}}", Escape($"generated by DocWiz on {DateTime.Now:yyyy-MM-dd HH:mm}"));
        return InlineAssets(html, project);
    }

    /// <summary>Minimal standalone wrapper for document-mode views (no sidebar/search).</summary>
    private static string DocumentShell(string content) =>
        """
        <!DOCTYPE html>
        <html lang="en" data-theme="light">
        <head>
        <meta charset="UTF-8">
        <meta name="viewport" content="width=device-width, initial-scale=1">
        <title>{{TITLE}} — {{CODE}}</title>
        <link rel="stylesheet" href="_dw/tokens.css">
        <link rel="stylesheet" href="_dw/site.css">
        </head>
        <body>
        <header>
          <span class="brand">{{PROJECT}}<small>{{CODE}} · v{{VERSION}}</small></span>
          <button id="themeBtn" type="button">Dark</button>
        </header>
        <main><article>
        """ + content + """
        </article></main>
        <footer><span>{{PROJECT}} · {{CODE}}</span><span>{{GENERATED}}</span></footer>
        <script src="_dw/site.js"></script>
        </body>
        </html>
        """;

    private static string InlineAssets(string html, DocProject project)
    {
        // CSS → inline <style>; JS → inline <script>; search dropped (irrelevant in one file).
        html = html
            .Replace("<link rel=\"stylesheet\" href=\"_dw/tokens.css\">", Style("tokens.css"))
            .Replace("<link rel=\"stylesheet\" href=\"_dw/site.css\">", Style("site.css"))
            .Replace("<script src=\"_dw/search-index.js\"></script>", "")
            .Replace("<script src=\"_dw/search.js\"></script>", "")
            .Replace("<script src=\"_dw/site.js\"></script>", Script("site.js"))
            .Replace("<script src=\"_dw/slides.js\"></script>", Script("slides.js"));

        // Embed referenced images as data URIs.
        html = ImageSrc.Replace(html, match =>
        {
            var rel = Uri.UnescapeDataString(match.Groups[1].Value);
            var file = Path.Combine(project.AssetsDir, rel);
            if (!File.Exists(file))
                return match.Value;
            var data = Convert.ToBase64String(File.ReadAllBytes(file));
            return $"src=\"data:{MimeOf(file)};base64,{data}\"";
        });

        return html;
    }

    private static string Style(string name) => "<style>" + SiteTemplates.Read(name) + "</style>";
    private static string Script(string name) => "<script>" + SiteTemplates.Read(name) + "</script>";

    private static string MimeOf(string path) => Path.GetExtension(path).ToLowerInvariant() switch
    {
        ".png" => "image/png",
        ".jpg" or ".jpeg" => "image/jpeg",
        ".gif" => "image/gif",
        ".svg" => "image/svg+xml",
        ".webp" => "image/webp",
        _ => "application/octet-stream",
    };

    private static string Escape(string text) => WebUtility.HtmlEncode(text);

    // The src prefix MUST match the asset URL LinkRewriter emits ({ProjectLayout.AssetsFolder}/…).
    // Both derive from the one ProjectLayout.AssetsFolder constant so the inliner can't silently
    // miss every image if the folder name ever changes (ADR-008, audit F4). Built at runtime (not
    // a [GeneratedRegex] literal) precisely so it stays tied to the constant.
    private static readonly Regex ImageSrc =
        new($"src=\"{Regex.Escape(ProjectLayout.AssetsFolder)}/([^\"]+)\"", RegexOptions.Compiled);
}
